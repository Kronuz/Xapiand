#!/usr/bin/env python3
"""Writes src/stopwords/builtin.inc from stopwords/<language>.txt.

Each list becomes one blob: its words, sorted by bytes without repeats, each followed by a NUL. The
words are the file's whitespace-separated tokens, as the loader reads an override. Run it from anywhere
after changing a list; tests/test_stopword_lists.cc fails when builtin.inc and the files differ.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "stopwords" / "builtin.inc"
PER_LINE = 6


def literal(word: bytes) -> str:
    text = word.decode("utf-8")  # an invalid byte sequence stops here
    out = []
    for ch in text:
        if ch in '"\\' or ord(ch) < 0x20 or ord(ch) == 0x7F:
            raise SystemExit(f"cannot embed {text!r}: control, quote or backslash character")
        out.append(ch)
    return '"' + "".join(out) + '\\0"'


def main() -> int:
    lines = [
        "// Generated by src/stopwords/generate.py from stopwords/*.txt; do not edit.",
        "",
    ]
    names = []
    for path in sorted((ROOT / "stopwords").glob("*.txt")):
        words = sorted(set(path.read_bytes().split()))
        names.append(path.stem)
        lines.append(f"inline constexpr char {path.stem}_words[] =")
        for i in range(0, len(words), PER_LINE):
            chunk = " ".join(literal(w) for w in words[i : i + PER_LINE])
            end = ";" if i + PER_LINE >= len(words) else ""
            lines.append(f"\t{chunk}{end}")
        lines.append("")
    lines.append("inline constexpr Builtin builtin[] = {")
    for name in names:
        lines.append(f'\tmake_builtin("{name}", {name}_words),')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
